def build() -> list[dict]:
    rows: list[dict] = []
    for scenario in SCENARIOS:
        sid, category, difficulty, has_order, first, second, expected = scenario
        for index, text in enumerate((first, second), start=1):
            rows.append(
                {
                    "id": f"{sid}-{index}",
                    "category": category,
                    "difficulty": difficulty,
                    "order_present": has_order,
                    "input": text,
                    "expected": expected,
                }
            )
    return rows


def main() -> None:
    rows = build()
    assert len(rows) == 100, len(rows)
    path = Path(__file__).parent / "heldout100_cases.jsonl"
    path.write_text(
        "\n".join(json.dumps(row, ensure_ascii=False) for row in rows) + "\n",
        encoding="utf-8",
    )
    counts: dict[str, int] = {}
    for row in rows:
        counts[row["category"]] = counts.get(row["category"], 0) + 1
    print(json.dumps({"total": len(rows), "by_category": counts}, ensure_ascii=False))


if __name__ == "__main__":
    main()
